import os
import pandas as pd
import sacrebleu
import torch

from google import genai
from google.genai import types
from google.colab import userdata
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM

# Read the API key securely from Colab Secrets.
GEMINI_API_KEY = userdata.get("GEMINI_API_KEY")
if not GEMINI_API_KEY:
    raise ValueError(
        "GEMINI_API_KEY was not found. Add it in Google Colab Secrets "
        "and enable notebook access."
    )

gemini_client = genai.Client(api_key=GEMINI_API_KEY)

# Keep the model name in one place so it can be changed if needed.
GEMINI_MODEL = "gemini-3.5-flash"

print("Libraries imported and Gemini client configured.")

"""## 5. Load the NLLB-200 translation model

We use `facebook/nllb-200-distilled-600M`, a multilingual sequence-to-sequence model.

The model is loaded once and reused for each translation. This avoids downloading and initializing it every time a user submits text.

For this notebook, we use a small set of language codes. The code list can be extended to other languages supported by NLLB-200.
"""

MODEL_NAME = "facebook/nllb-200-distilled-600M"

print("Loading NLLB-200. The first run may take a few minutes...")
tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
translation_model = AutoModelForSeq2SeqLM.from_pretrained(MODEL_NAME)

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
translation_model = translation_model.to(DEVICE)
translation_model.eval()

print(f"NLLB-200 loaded successfully on {DEVICE}.")

"""## 6. Supported language codes

NLLB uses language identifiers rather than ordinary language names. The dictionary below connects the names shown in the interface to the identifiers expected by the model.

The selected source language is set on the tokenizer before translation. The target language is passed through `forced_bos_token_id`.
"""

LANG_CODES = {
    "English": "eng_Latn",
    "Hindi": "hin_Deva",
    "Arabic": "arb_Arab",
    "Spanish": "spa_Latn",
    "French": "fra_Latn",
    "Swahili": "swh_Latn",
    "Tagalog": "tgl_Latn"
}

print("Languages available:", ", ".join(LANG_CODES.keys()))

"""## 7. Stage 1: baseline machine translation

The first function translates the input using NLLB-200. This is our baseline: it gives us a direct translation before any plain-language rewriting or slang localization takes place.

We use inference mode because the model is being used for prediction, not training.
"""

def translate_text(text: str, src_lang: str, tgt_lang: str) -> str:
    """Translate text from a supported source language to a target language."""
    if not isinstance(text, str) or not text.strip():
        raise ValueError("Please enter some text.")
    if src_lang not in LANG_CODES or tgt_lang not in LANG_CODES:
        raise ValueError("The selected language is not supported in this notebook.")

    tokenizer.src_lang = LANG_CODES[src_lang]
    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=512
    ).to(DEVICE)

    with torch.inference_mode():
        generated_tokens = translation_model.generate(
            **inputs,
            forced_bos_token_id=tokenizer.convert_tokens_to_ids(LANG_CODES[tgt_lang]),
            max_new_tokens=256
        )

    return tokenizer.batch_decode(
        generated_tokens,
        skip_special_tokens=True
    )[0].strip()

"""## 8. Stage 2: administrative language simplification

A direct translation may still contain formal or difficult wording. The next function asks Gemini to rewrite the translated text in simpler language.

The prompt emphasizes meaning preservation. In particular, the model is told not to change dates, numbers, fees, names, deadlines or legal requirements. This instruction reduces the risk of a rewrite changing important details, although the output must still be checked against the source.
"""

def simplify_administrative_text(text: str, target_language: str) -> str:
    """Rewrite translated administrative text in plain, clear language."""
    prompt = f"""
You help everyday citizens and newcomers understand official documents.

Rewrite the text below in {target_language} using simple, clear,
everyday language.

Rules:
- Preserve the original meaning and all important conditions.
- Keep dates, amounts, numbers, names, deadlines and requirements unchanged.
- Do not remove warnings, exceptions or eligibility conditions.
- Break long sentences into shorter sentences or bullet points when useful.
- Do not invent information or give legal advice.
- Output only the simplified explanation.

Text:
{text}
"""

    response = gemini_client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt,
        config=types.GenerateContentConfig()
    )

    if not response.text:
        raise RuntimeError("Gemini returned an empty response.")
    return response.text.strip()

"""## 9. Alternative mode: slang and casual-language localization

Informal language can contain idioms, shortened phrases and culturally specific expressions. A literal translation may sound unnatural or communicate the wrong tone.

In this mode, Gemini receives the original text and is asked to express its meaning naturally in the target language. The goal is to preserve the intent and conversational tone rather than translate every word literally.
"""

def translate_and_localize_slang(text: str, target_language: str) -> str:
    """Translate informal text into natural, conversational target-language wording."""
    if not isinstance(text, str) or not text.strip():
        raise ValueError("Please enter some text.")

    prompt = f"""
You are a multilingual localization assistant.

Translate and adapt the following informal or slang-heavy message into
natural, conversational {target_language}.

Rules:
- Preserve the speaker's intended meaning and tone.
- Do not translate idioms or slang word for word if that sounds unnatural.
- Use an expression that a fluent speaker of {target_language} would understand.
- Do not add new facts or change the speaker's intent.
- Output only the localized message.

Message:
{text}
"""

    response = gemini_client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt,
        config=types.GenerateContentConfig()
    )

    if not response.text:
        raise RuntimeError("Gemini returned an empty response.")
    return response.text.strip()

"""## 10. Combine the stages into one pipeline

The pipeline keeps the two modes separate:

- **Administrative Jargon Simplification:** NLLB translates the source text, then Gemini simplifies that translation.
- **Slang & Casual Localization:** Gemini translates and localizes the original message directly.

For administrative text, we return both the direct translation and the simplified version so the user can compare them.
"""

def run_pipeline(
    text: str,
    mode: str,
    src_lang: str,
    tgt_lang: str
):
    """Run the selected workflow and return baseline and final text."""
    if not text or not text.strip():
        raise ValueError("Please enter some text.")

    if mode == "Administrative Jargon Simplification":
        baseline = translate_text(text, src_lang, tgt_lang)
        final_output = simplify_administrative_text(baseline, tgt_lang)
        return baseline, final_output

    if mode == "Slang & Casual Localization":
        # NLLB output is shown as a comparison baseline.
        baseline = translate_text(text, src_lang, tgt_lang)
        final_output = translate_and_localize_slang(text, tgt_lang)
        return baseline, final_output

    raise ValueError("Please select a valid translation mode.")

"""## 11. Build a small administrative-language test set

We prepared two example administrative texts for an initial qualitative test. They represent two contexts:

- Visa and immigration requirements.
- Healthcare and insurance authorization.

Each example includes a human-written reference translation in Hindi and Spanish. These references let us compare the direct NLLB translation with a reference translation using chrF.

**Dataset limitation:** two examples are not enough to establish general translation quality. We use them as demonstrations and a small initial check, not as proof that the system is reliable for all official documents.
"""

