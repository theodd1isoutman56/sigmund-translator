"""## 15. Additional translation evaluation with OPUS-100

To add a wider multilingual evaluation, we load an English-to-Hindi test split from OPUS-100 (`Helsinki-NLP/opus-100`). We use a small 20-example subset to keep the run manageable and entirely ungated.

This evaluation checks the **NLLB baseline translation** against the Hindi reference sentences. It does not evaluate Gemini's simplification quality.

Unlike gated datasets that require authentication tokens, OPUS-100 is publicly accessible and downloads instantly for any hackathon judge running this notebook.
"""

from datasets import load_dataset

print("Loading the English–Hindi evaluation sample...")

# Load 20 English-Hindi test pairs from an ungated Parquet dataset
eval_dataset = load_dataset(
    "Helsinki-NLP/opus-100",
    "en-hi",
    split="test[:20]"
)

flores_sources = [row["translation"]["en"] for row in eval_dataset]
flores_references = [row["translation"]["hi"] for row in eval_dataset]

print(f"Loaded {len(flores_sources)} source sentences.")

"""## 16. Translate and score the OPUS-100 sample

We translate each English sentence into Hindi with NLLB-200 and calculate corpus-level chrF against the OPUS-100 references.

This gives us a separate benchmark result from the two administrative examples. It is still a small subset, so the score should be interpreted as an initial experiment rather than a definitive ranking of the model.
"""

flores_hypotheses = []

for sentence in flores_sources:
    flores_hypotheses.append(
        translate_text(sentence, "English", "Hindi")
    )

flores_score = sacrebleu.corpus_chrf(
    flores_hypotheses,
    [flores_references]
)

print("FLORES+ English → Hindi evaluation")
print(f"Examples: {len(flores_sources)}")
print(f"NLLB baseline chrF: {flores_score.score:.2f}")

"""## 17. Inspect OPUS-100 translation examples

We print a few source, model and reference examples. This helps us see what the metric does not show, such as differences in phrasing or word choice.

A high overlap score does not guarantee that a translation is perfect. Important text should still be checked by a fluent speaker or qualified reviewer.
"""

for i in range(min(5, len(flores_sources))):
    print(f"\nExample {i + 1}")
    print("English source:       ", flores_sources[i])
    print("NLLB Hindi output:    ", flores_hypotheses[i])
    print("FLORES+ Hindi reference:", flores_references[i])

"""## 18. What we learned from the evaluation

The evaluation has two different purposes:

1. The administrative examples let us inspect the effect of simplifying formal text and compare baseline translations with human references.
2. OPUS-100 gives us a small reference-based translation benchmark for NLLB.

There is an important distinction: chrF evaluates translation overlap, not simplicity. To evaluate whether Gemini genuinely makes official text easier to understand, we would need a larger set of documents and a human review process with criteria for clarity and meaning preservation.

We therefore do not claim that the current chrF results prove the simplification stage is better.

## 19. Build the interactive demo

The Gradio interface lets a user choose a mode, select source and target languages, enter text and compare the baseline with the final output.

For administrative text, the final output is the simplified translation. For slang, the final output is Gemini's localized version.

The app is not launched automatically when the notebook is run. Set `RUN_APP = True` in the next cell when you want to open it.
"""

import gradio as gr

def demo_interface(text, mode, src_lang, tgt_lang):
    try:
        baseline, final_output = run_pipeline(
            text=text,
            mode=mode,
            src_lang=src_lang,
            tgt_lang=tgt_lang
        )
        return baseline, final_output
    except Exception as error:
        message = f"Unable to process this text: {error}"
        return message, message

with gr.Blocks(theme=gr.themes.Soft()) as demo:
    gr.Markdown(
        "# 🌐 Sigmund Translator\n"
        "### Understand official language. Localize everyday language."
    )

    mode_selector = gr.Radio(
        choices=[
            "Administrative Jargon Simplification",
            "Slang & Casual Localization"
        ],
        value="Administrative Jargon Simplification",
        label="Select a mode"
    )

    with gr.Row():
        src_dropdown = gr.Dropdown(
            choices=list(LANG_CODES.keys()),
            value="English",
            label="Source language"
        )
        tgt_dropdown = gr.Dropdown(
            choices=list(LANG_CODES.keys()),
            value="Hindi",
            label="Target language"
        )

    input_box = gr.Textbox(
        lines=4,
        label="Enter text",
        placeholder="Paste an official message or an informal expression..."
    )

    submit_btn = gr.Button("Process text", variant="primary")

    with gr.Row():
        baseline_out = gr.Textbox(
            lines=7,
            label="Baseline translation (NLLB-200)"
        )
        final_out = gr.Textbox(
            lines=7,
            label="Sigmund Translator"
        )

    submit_btn.click(
        fn=demo_interface,
        inputs=[input_box, mode_selector, src_dropdown, tgt_dropdown],
        outputs=[baseline_out, final_out]
    )

print("Gradio interface is ready.")

